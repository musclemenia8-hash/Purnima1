// Helper to compute transparent jewellery price
function computePrice(weight: number, makingRatePercent: number = 0.12) {
  const goldVal = Math.round(weight * BASE_GOLD_RATE_22K);
  const making = Math.round(goldVal * makingRatePercent);
  const taxable = goldVal + making;
  const gst = Math.round(taxable * 0.03); // 3% standard GST on gold jewellery
  const total = taxable + gst;
  return { goldVal, making, gst, total };
}

